def read(path, expected=None):
    path=Path(path)
    require(path.is_absolute()and path.resolve()==path and not any(p.is_symlink()for p in (path,*path.parents)),
            'Exact ordinary source path')
    fd=os.open(path,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK)
    try:
        before=os.fstat(fd)
        require(stat.S_ISREG(before.st_mode)and before.st_nlink==1 and 0<=before.st_size<=8*2**20,
                'Bounded ordinary source file')
        with os.fdopen(fd,'rb',closefd=False)as stream:data=stream.read(8*2**20+1)
        after=os.fstat(fd);current=path.stat()
        require(len(data)==before.st_size and all(getattr(before,k)==getattr(after,k)==getattr(current,k)
            for k in ('st_dev','st_ino','st_size','st_mtime_ns','st_ctime_ns')), 'Stable complete source file')
    finally:os.close(fd)
    digest=hashlib.sha256(data).hexdigest()
    require(expected is None or expected==digest,'Exact prior source pin')
    return data,dict(path=str(path),sha256=digest,bytes=len(data))


