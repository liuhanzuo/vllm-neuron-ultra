"""Real frozen-dispatch integration with synthetic native authentication evidence.

Original SDK/native files are never opened. The existing Interpreter fixture
uses generated bytes and maps; its other tests are not inherited or rerun.
"""
import copy
import importlib
import importlib._bootstrap as bootstrap
import importlib.machinery as machinery
import importlib.util as util
from pathlib import Path
import sys
import types
import unittest
from unittest.mock import patch

sys.path.insert(0,str(Path(__file__).resolve().parent))
import check_nemotron4b_interpreter_origin_policy_v1 as fixture
import nemotron4b_interpreter_origin_policy_v1 as interpreter
import nemotron4b_bootstrap_dispatch_origin_v1 as dispatch_origin
import nemotron4b_import_router_v4 as routing
import nemotron4b_import_context_v3 as dispatch
from nemotron4b_helper_dependency_catalog_v1 import source
from nemotron4b_process_handshake_v1 import require


class Bootstrap(unittest.TestCase):
    def setUp(self):
        fixture.Interpreter.setUp(self)
        module=sys.modules['_frozen_importlib']
        self.manifest['modules']['_frozen_importlib']=fixture.module_row(module.__spec__,module)
        self.ip=fixture.Interpreter.make(self)
        self.ip.bind_preloaded('_frozen_importlib',module)
        self.dispatch_manifest=dispatch_origin.description()

    def make(self):
        return dispatch_origin.BootstrapDispatchPolicy(self.ip,self.dispatch_manifest)

    def test_original_dispatch_matches_authenticated_frozen_definition(self):
        p=self.make()
        p.authenticate_bootstrap(bootstrap._find_spec)
        self.assertTrue(p.result()['original_dispatcher_authenticated'])
        self.assertFalse(p.result()['complete_preloaded_source_provenance'])
        with self.assertRaisesRegex(ValueError,'One dispatcher'):p.authenticate_bootstrap(bootstrap._find_spec)

    def test_unbound_bootstrap_cannot_authenticate(self):
        self.ip.module_objects.pop('_frozen_importlib')
        with self.assertRaisesRegex(ValueError,'already be authenticated'):self.make()

    def test_reviewed_definition_and_defaults_required(self):
        for key in ('definition_sha256','function_state'):
            old=copy.deepcopy(self.dispatch_manifest[key])
            try:
                self.dispatch_manifest[key]='changed'
                with self.assertRaisesRegex(ValueError,'reviewed frozen'):self.make()
            finally:self.dispatch_manifest[key]=old

    def test_matching_code_with_different_globals_rejected(self):
        old=bootstrap._find_spec
        clone=types.FunctionType(old.__code__,dict(old.__globals__),old.__name__,old.__defaults__,old.__closure__)
        with patch.object(bootstrap,'_find_spec',clone),patch.object(util,'_find_spec',clone):
            with self.assertRaisesRegex(ValueError,'module globals'):self.make()

    def test_equal_replacement_code_object_rejected_after_binding(self):
        p=self.make();old=p.original.__code__
        try:
            p.original.__code__=old.replace()
            self.assertEqual(p.original.__code__,old)
            with self.assertRaisesRegex(ValueError,'code identity'):p.authenticate_bootstrap(p.original)
        finally:p.original.__code__=old

    def test_changed_defaults_rejected_after_binding(self):
        p=self.make();old=p.original.__defaults__
        try:
            p.original.__defaults__=(None,'changed')
            with self.assertRaisesRegex(ValueError,'defaults retained'):p.authenticate_bootstrap(p.original)
        finally:p.original.__defaults__=old

    def test_wrong_callback_or_util_alias_rejected(self):
        p=self.make()
        with self.assertRaisesRegex(ValueError,'Both original'):p.authenticate_bootstrap(lambda *a:None)
        with patch.object(util,'_find_spec',lambda *a:None):
            with self.assertRaisesRegex(ValueError,'Both original'):p.authenticate_bootstrap(p.original)
        self.assertFalse(p.authenticated)

    def test_canonical_registry_alias_replacement_rejected(self):
        p=self.make()
        with patch.dict(sys.modules,{'importlib._bootstrap':types.ModuleType('importlib._bootstrap')}):
            with self.assertRaisesRegex(ValueError,'module objects'):p.authenticate_bootstrap(p.original)

    def test_serial_guard_denial_precedes_frozen_code_access(self):
        def deny():raise RuntimeError('synthetic slot denied')
        self.ip.guard=deny
        with patch.object(dispatch_origin,'description')as describe:
            with self.assertRaisesRegex(RuntimeError,'slot denied'):self.make()
            describe.assert_not_called()

    def context(self,policy):
        path=self.root/'nano_dispatch_fixture.py'
        path.write_text('answer = 42\n')
        _,row=source(path)
        modules={'nano_dispatch_fixture':dict(row,path=str(path),kind='source',package=False)}
        def deny(*a):raise ValueError('Fixture denies native/custom imports')
        router=routing.ImportRouter(finders=list(sys.meta_path),modules=modules,namespaces={},
            guard=lambda:None,authorize_finder=self.ip.authorize_finder,
            authorize_builtin=self.ip.authorize_builtin,authorize_native=deny,authorize_custom=deny)
        return dispatch.DispatchContext(router,authenticate_bootstrap=policy.authenticate_bootstrap,
            audit_modules=lambda:None,audit_environment=lambda:None,approve_existing_spec=deny)

    def test_actual_dispatch_context_installs_imports_source_and_restores(self):
        p=self.make();context=self.context(p);original=bootstrap._find_spec
        sys.path.insert(0,str(self.root))
        try:
            with context.installed()as report:
                self.assertIs(bootstrap._find_spec,context.hook)
                self.assertIs(util._find_spec,context.hook)
                module=importlib.import_module('nano_dispatch_fixture')
                self.assertEqual(module.answer,42)
                self.assertIsInstance(module.__loader__,routing.PinnedSourceLoader)
                self.assertTrue(p.result()['original_dispatcher_authenticated'])
            self.assertTrue(report['dispatch_context_completed'])
        finally:
            sys.path.remove(str(self.root));sys.modules.pop('nano_dispatch_fixture',None)
        self.assertIs(bootstrap._find_spec,original);self.assertIs(util._find_spec,original)
        p.check_original()

    def test_actual_context_preserves_body_exception_and_restores(self):
        p=self.make();context=self.context(p);original=bootstrap._find_spec
        error=ImportError('original fixture body failure')
        with self.assertRaises(ImportError)as caught:
            with context.installed():raise error
        self.assertIs(caught.exception,error)
        self.assertIs(bootstrap._find_spec,original);self.assertIs(util._find_spec,original)
        self.assertFalse(context.provenance['dispatch_context_completed'])

    def test_manifest_snapshot_cannot_be_rebound(self):
        p=self.make();self.dispatch_manifest['definition_sha256']='0'*64
        p.authenticate_bootstrap(p.original)
        self.assertNotEqual(p.manifest['definition_sha256'],'0'*64)


if __name__=='__main__':unittest.main(verbosity=2)
